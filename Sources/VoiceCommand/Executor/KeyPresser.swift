/// Synthetic key and scroll events (CGEvent). Key codes are ANSI positions.
enum KeyPresser {
    static let keyCodes: [String: CGKeyCode] = [
        "a": 0, "s": 1, "d": 2, "f": 3, "h": 4, "g": 5, "z": 6, "x": 7, "c": 8, "v": 9, "b": 11, "q": 12,
        "w": 13, "e": 14, "r": 15, "y": 16, "t": 17, "1": 18, "2": 19, "3": 20, "4": 21, "6": 22, "5": 23,
        "=": 24, "9": 25, "7": 26, "-": 27, "8": 28, "0": 29, "]": 30, "o": 31, "u": 32, "[": 33, "i": 34,
        "p": 35, "l": 37, "j": 38, "'": 39, "k": 40, ";": 41, "\\": 42, ",": 43, "/": 44, "n": 45, "m": 46,
        ".": 47, "`": 50,
        "return": 36, "enter": 36, "tab": 48, "space": 49, "delete": 51, "backspace": 51, "escape": 53,
        "forwarddelete": 117, "home": 115, "end": 119, "pageup": 116, "pagedown": 121,
        "left": 123, "right": 124, "down": 125, "up": 126,
        "f1": 122, "f2": 120, "f3": 99, "f4": 118, "f5": 96, "f6": 97, "f7": 98, "f8": 100,
        "f9": 101, "f10": 109, "f11": 103, "f12": 111,
    ]

    static func press(_ combo: KeyCombo) -> Bool {
        guard let code = keyCodes[combo.key] else { return false }
        var flags: CGEventFlags = []
        if combo.command { flags.insert(.maskCommand) }
        if combo.shift { flags.insert(.maskShift) }
        if combo.option { flags.insert(.maskAlternate) }
        if combo.control { flags.insert(.maskControl) }
        let src = CGEventSource(stateID: .combinedSessionState)
        guard let down = CGEvent(keyboardEventSource: src, virtualKey: code, keyDown: true),
              let up = CGEvent(keyboardEventSource: src, virtualKey: code, keyDown: false) else { return false }
        down.flags = flags
        up.flags = flags
        down.post(tap: .cghidEventTap)
        up.post(tap: .cghidEventTap)
        return true
    }

    static func press(_ keys: String) -> Bool {
        guard let combo = KeyCombo.parse(keys) else { return false }
        return press(combo)
    }

    /// Backspace `count` times (clear_typed). Never select-all.
    static func backspace(_ count: Int) {
        let src = CGEventSource(stateID: .combinedSessionState)
        for _ in 0..<count {
            CGEvent(keyboardEventSource: src, virtualKey: 51, keyDown: true)?.post(tap: .cghidEventTap)
            CGEvent(keyboardEventSource: src, virtualKey: 51, keyDown: false)?.post(tap: .cghidEventTap)
            usleep(1500)
        }
    }

    /// Scroll the window at `point` (screen coordinates, top-left origin).
    static func scroll(down: Bool, page: Bool, at point: CGPoint?) {
        let lines: Int32 = page ? 15 : 4
        guard let ev = CGEvent(scrollWheelEvent2Source: nil, units: .line, wheelCount: 1, wheel1: down ? -lines : lines, wheel2: 0, wheel3: 0) else { return }
        if let point { ev.location = point }
        ev.post(tap: .cghidEventTap)
    }

    /// Click at a screen point (top-left origin). Last-resort focus for a text input.
    static func click(at point: CGPoint) {
        let src = CGEventSource(stateID: .combinedSessionState)
        CGEvent(mouseEventSource: src, mouseType: .leftMouseDown, mouseCursorPosition: point, mouseButton: .left)?.post(tap: .cghidEventTap)
        CGEvent(mouseEventSource: src, mouseType: .leftMouseUp, mouseCursorPosition: point, mouseButton: .left)?.post(tap: .cghidEventTap)
    }
}

/// Paste text with clipboard save and restore.
///
/// Both the paste write and the restore write are marked transient and auto-generated
/// (nspasteboard.org) so clipboard managers ignore them. The restore happens only once
/// the pasteboard changeCount has stayed the same for 300 ms, and gives up after 1 s.
enum PasteService {
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private struct Saved { let items: [[NSPasteboard.PasteboardType: Data]] }

    private static func save(_ pb: NSPasteboard) -> Saved {
        Saved(items: (pb.pasteboardItems ?? []).map { item in
            var d: [NSPasteboard.PasteboardType: Data] = [:]
            for t in item.types { if let data = item.data(forType: t) { d[t] = data } }
            return d
        })
    }

    private static func write(_ pb: NSPasteboard, items: [[NSPasteboard.PasteboardType: Data]]) {
        pb.clearContents()
        let objs: [NSPasteboardItem] = items.map { dict in
            let item = NSPasteboardItem()
            for (t, data) in dict { item.setData(data, forType: t) }
            item.setData(Data(), forType: transient)
            item.setData(Data(), forType: autoGenerated)
            return item
        }
        if objs.isEmpty {
            let item = NSPasteboardItem()
            item.setData(Data(), forType: transient)
            item.setData(Data(), forType: autoGenerated)
            pb.writeObjects([item])
        } else {
            pb.writeObjects(objs)
        }
    }

    /// Leave text on the clipboard for the person (a normal entry, not transient), so words
    /// that couldn't be typed aren't lost.
    static func copy(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
    }

    /// Paste into whatever has keyboard focus. Trailing newlines are stripped
    /// (a trailing newline auto-submits in Claude Code).
    static func paste(_ text: String) async {
        let clean = text.replacingOccurrences(of: "[\\r\\n]+$", with: "", options: .regularExpression)
        let pb = NSPasteboard.general
        let saved = save(pb)
        write(pb, items: [[.string: Data(clean.utf8)]])
        let ours = pb.changeCount
        _ = KeyPresser.press(KeyCombo(command: true, key: "v"))

        // Restore once the target app has read the paste.
        let start = Date()
        var lastCount = pb.changeCount
        var stableSince = Date()
        while Date().timeIntervalSince(start) < 1.0 {
            try? await Task.sleep(nanoseconds: 50_000_000)
            if pb.changeCount != lastCount { lastCount = pb.changeCount; stableSince = Date() }
            if Date().timeIntervalSince(stableSince) >= 0.3 { break }
        }
        // Someone else wrote to the clipboard meanwhile: keep theirs.
        guard pb.changeCount == ours else { return }
        write(pb, items: saved.items)
    }
}
